-- LedgerForge core schema. Portable across PostgreSQL and H2 (PostgreSQL mode).
-- Money is stored as BIGINT minor units (cents) — never floating point.

CREATE TABLE tenants (
    id          UUID PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    audit_head_index  BIGINT,          -- latest audit event; lets verification detect deleted tail events
    audit_head_hash   VARCHAR(64)
);

CREATE TABLE api_keys (
    id          UUID PRIMARY KEY,
    tenant_id   UUID NOT NULL REFERENCES tenants (id),
    key_prefix  VARCHAR(12) NOT NULL UNIQUE,   -- public lookup handle
    key_hash    VARCHAR(64) NOT NULL,          -- SHA-256 of the full key; plaintext is never stored
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE accounts (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenants (id),
    name            VARCHAR(100) NOT NULL,
    currency        VARCHAR(3) NOT NULL,
    allow_negative  BOOLEAN NOT NULL,          -- true only for funding/settlement accounts
    balance         BIGINT NOT NULL,           -- cached; must always equal SUM(postings.amount)
    version         BIGINT NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_accounts_tenant ON accounts (tenant_id);

CREATE TABLE ledger_transactions (
    id               UUID PRIMARY KEY,
    tenant_id        UUID NOT NULL REFERENCES tenants (id),
    from_account_id  UUID NOT NULL REFERENCES accounts (id),
    to_account_id    UUID NOT NULL REFERENCES accounts (id),
    amount           BIGINT NOT NULL CHECK (amount > 0),
    currency         VARCHAR(3) NOT NULL,
    reference        VARCHAR(64),
    description      VARCHAR(140),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_txn_tenant ON ledger_transactions (tenant_id, created_at);

-- Double entry: every transaction has postings that sum to exactly zero.
CREATE TABLE postings (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenants (id),
    transaction_id  UUID NOT NULL REFERENCES ledger_transactions (id),
    account_id      UUID NOT NULL REFERENCES accounts (id),
    amount          BIGINT NOT NULL CHECK (amount <> 0),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_postings_account ON postings (account_id, created_at);
CREATE INDEX idx_postings_tenant ON postings (tenant_id);

CREATE TABLE idempotency_keys (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenants (id),
    idem_key        VARCHAR(64) NOT NULL,
    request_hash    VARCHAR(64) NOT NULL,
    transaction_id  UUID NOT NULL REFERENCES ledger_transactions (id),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency UNIQUE (tenant_id, idem_key)
);

-- Tamper-evident, per-tenant hash chain.
CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      UUID NOT NULL REFERENCES tenants (id),
    chain_index    BIGINT NOT NULL,
    event_type     VARCHAR(40) NOT NULL,
    payload        VARCHAR(4000) NOT NULL,
    created_at_ms  BIGINT NOT NULL,
    prev_hash      VARCHAR(64) NOT NULL,
    hash           VARCHAR(64) NOT NULL,
    CONSTRAINT uq_audit_chain UNIQUE (tenant_id, chain_index)
);
